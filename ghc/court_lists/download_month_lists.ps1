foreach ($f in $files) {
  $out = Join-Path $dest $f
  if (Test-Path $out) { continue }
  try {
    Invoke-WebRequest -Uri ("https://ghconline.gov.in/" + $f) -OutFile $out -UserAgent "Recourse-research/1.0 (low-rate)" -TimeoutSec 90
    Write-Host ("ok     " + $f)
  } catch { Write-Host ("FAILED " + $f + " : " + $_.Exception.Message) }
  Start-Sleep -Seconds 3
}
Write-Host "finished"
